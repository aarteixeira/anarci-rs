#!/usr/bin/env python3
"""Retain full cached license texts for the resolved Python runtime dependencies.

Uses locked offline Cargo metadata/tree output. This reads registry license files
and VCS metadata only; it does not inspect scientific data or compile packages.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
TARGETS = (
    "aarch64-apple-darwin", "aarch64-unknown-linux-gnu",
    "x86_64-apple-darwin", "x86_64-unknown-linux-gnu",
)
LEGAL_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE", "COPYRIGHT")


def cargo(*args):
    return subprocess.check_output(["cargo", *args], cwd=ROOT, text=True)


def runtime_graph(model):
    packages = set()
    for target in TARGETS:
        command = ["tree", "--locked", "--offline", "-p", "anarci-py", "--edges", "normal",
                   "--prefix", "none", "--target", target, "--format", "{p}"]
        if model:
            command += ["--features", "learned-model"]
        for line in cargo(*command).splitlines():
            match = re.match(r"^([^ ]+) v([^ ]+)", line)
            if not match:
                raise ValueError("unexpected cargo tree package record")
            packages.add(match.groups())
    return packages


def legal_files(package):
    root = Path(package["manifest_path"]).parent
    files = []
    for path in root.rglob("*"):
        if path.name.upper().startswith(LEGAL_PREFIXES) and path.is_file():
            # A crate archive cannot redirect this read outside its registry directory.
            path.resolve().relative_to(root.resolve())
            files.append(path)
    if package.get("license_file"):
        path = root / package["license_file"]
        path.resolve().relative_to(root.resolve())
        if path.is_file():
            files.append(path)
    return sorted(set(files), key=lambda path: path.relative_to(root).as_posix())


def commit(package):
    path = Path(package["manifest_path"]).parent / ".cargo_vcs_info.json"
    if not path.is_file():
        return None
    return json.loads(path.read_text())["git"]["sha1"]


def generate():
    metadata = json.loads(cargo("metadata", "--locked", "--offline", "--format-version", "1",
                                "--features", "anarci-py/learned-model"))
    default = runtime_graph(False)
    expanded = runtime_graph(True) | default
    resolved = {(package["name"], package["version"]) for package in metadata["packages"]}
    if expanded - resolved:
        raise ValueError("runtime graph has packages absent from locked metadata")
    registry = [package for package in metadata["packages"]
                if (package.get("source") or "").startswith("registry+")]
    selected = sorted((package for package in registry
                       if (package["name"], package["version"]) in expanded),
                      key=lambda package: (package["name"], package["version"]))
    lock_hash = hashlib.sha256((ROOT / "Cargo.lock").read_bytes()).hexdigest()
    output = [
        "Rust third-party license materials",
        "Generated by scripts/generate_rust_notices.py; regenerate after dependency changes.",
        "Scope: locked anarci-py normal dependencies, default and learned-model features.",
        "Targets: " + ", ".join(TARGETS),
        "Cargo.lock SHA-256: " + lock_hash,
        "Registry packages retained: " + str(len(selected)),
        "Local workspace code is covered by LICENSE; HMMER/Easel by their separate notices.",
        "Optional-model dependency texts are retained even in the default wheel.",
        "", ]
    for package in selected:
        source = package
        files = legal_files(package)
        shared = None
        if not files:
            revision = commit(package)
            for candidate in sorted(registry, key=lambda item: (item["name"], item["version"])):
                if (revision and package.get("repository")
                        and candidate.get("repository") == package["repository"]
                        and candidate.get("license") == package.get("license")
                        and commit(candidate) == revision):
                    files = legal_files(candidate)
                    if files:
                        source = candidate
                        shared = revision
                        break
        if not files:
            raise ValueError("missing full license text for " + package["name"] + " " + package["version"])
        identifier = package["name"] + " " + package["version"]
        scope = "default" if (package["name"], package["version"]) in default else "learned-model"
        output += ["=" * 78, "Package: " + identifier,
                   "SPDX license: " + (package.get("license") or "declared license file"),
                   "Feature scope: " + scope]
        if package.get("repository"):
            output.append("Repository: " + package["repository"])
        if shared:
            output.append("Shared upstream license source: " + source["name"] + " " + source["version"]
                          + "; identical repository, VCS commit " + shared + " and SPDX license.")
        root = Path(source["manifest_path"]).parent
        for path in files:
            output += ["", "--- " + source["name"] + "/" + path.relative_to(root).as_posix() + " ---",
                       path.read_text(encoding="utf-8").rstrip("\n"), ""]
    return "\n".join(output).rstrip("\n") + "\n", len(selected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the saved notice is current")
    parser.add_argument("--output", type=Path, default=ROOT / "licenses/RUST-THIRD-PARTY.txt")
    args = parser.parse_args()
    content, count = generate()
    if args.check:
        if not args.output.is_file() or args.output.read_text() != content:
            raise SystemExit("Rust notices differ; regenerate with scripts/generate_rust_notices.py")
    else:
        args.output.write_text(content)
    print(f"Rust notices {'verified' if args.check else 'generated'}: {count} registry packages")


if __name__ == "__main__":
    main()
